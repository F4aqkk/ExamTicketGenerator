def build_questions(topic: Topic, tags: dict[str, Tag]) -> list[Question]:
    """Вопросы темы: сначала настоящие, потом тестовые до нужного числа."""
    questions = []
    for difficulty in (1, 2, 3):
        real = [q for q in QUESTIONS[topic.name] if q[0] == difficulty]
        for _, text, answer, tag_names in real:
            questions.append(
                Question(
                    text=text,
                    answer=answer,
                    difficulty=difficulty,
                    task_type="Теория",
                    topic=topic,
                    tags=[tags[name] for name in tag_names],
                )
            )
        for n in range(len(real) + 1, PER_LEVEL + 1):
            questions.append(
                Question(
                    text=f"{topic.name}: тестовый вопрос {n} "
                    f"(сложность {difficulty})",
                    answer=f"Ответ на тестовый вопрос {n}",
                    difficulty=difficulty,
                    task_type="Практика",
                    topic=topic,
                )
            )
    return questions


def count_rows(session, model) -> int:
    """Сколько строк в таблице модели."""
    return session.scalar(select(func.count()).select_from(model))


def main() -> None:
    """Пересоздать таблицы, заполнить их и сделать пробную генерацию."""
    Base.metadata.drop_all(engine)  # удалить старые таблицы
    Base.metadata.create_all(engine)  # создать по новым моделям
    with SessionLocal() as session:
        tag_names = ["определение", "сравнение", "код", "SQL"]
        tags = {name: Tag(name=name) for name in tag_names}
        for name in QUESTIONS:
            topic = Topic(name=name)
            session.add_all(build_questions(topic, tags))
        session.commit()  # все вопросы одной транзакцией

        start = time.perf_counter()
        GenerationService(session).create(
            "Пробная генерация",
            30,
            {1: 5, 2: 5, 3: 5},
        )
        seconds = time.perf_counter() - start

        for model in app.models.__all__:
            table = getattr(app.models, model)
            print(f"{table.__tablename__}: {count_rows(session, table)}")
        print(f"30 билетов по 15 вопросов составлены за {seconds:.2f} с")
    engine.dispose()  # закрыть соединение с файлом базы


if __name__ == "__main__":
    main()
